// scripts/capture-screenshots.mjs — re-capture the README screenshots in
// docs/images/ from a running `make demo-up` estate. See docs/images/README.md.
//
//     make screenshots                  # every image
//     make screenshots ONLY=findings    # one image, by file stem
//
// Needs the Chromium that matches playwright-core: `pnpm exec playwright-core
// install chromium` once. WEB_URL / API_URL / KESTREL_EMAIL / KESTREL_PASSWORD
// override the demo defaults.
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { chromium } from "playwright-core";

const WEB_URL = process.env.WEB_URL ?? "http://localhost:3010";
const API_URL = process.env.API_URL ?? "http://localhost:8010";
const EMAIL = process.env.KESTREL_EMAIL ?? "admin@kestrel.local";
const PASSWORD = process.env.KESTREL_PASSWORD ?? "kestrel-dev-password";
const ONLY = process.env.ONLY || null;
// Every image is published 1800px wide; rendering at width-scaled DPR lands
// there directly, with no resampling step.
const OUTPUT_WIDTH = 1800;
const BOTTOM_PADDING = 32;
const OUT_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "docs", "images");

async function api(token, route) {
  const response = await fetch(`${API_URL}/api/v1${route}`, {
    headers: token ? { Authorization: `Bearer ${token}` } : {},
  });
  if (!response.ok) throw new Error(`GET ${route}: ${response.status} ${await response.text()}`);
  return response.json();
}

async function login() {
  const response = await fetch(`${API_URL}/api/v1/auth/login`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ email: EMAIL, password: PASSWORD }),
  });
  if (!response.ok) throw new Error(`login failed: ${response.status} — is the demo up (make demo-up)?`);
  const body = await response.json();
  if (body.mfa_required) throw new Error("the capture account has MFA enrolled; use one without");
  return body.token;
}

async function allPeople(token) {
  const people = [];
  let cursor = null;
  do {
    const page = await api(token, `/identities?collapse=true&limit=100${cursor ? `&cursor=${cursor}` : ""}`);
    people.push(...page.items);
    cursor = page.next_cursor;
  } while (cursor);
  return people;
}

// Demo ids are regenerated by every `demo up`, so each run looks them up.
async function resolveIds(token) {
  const people = await allPeople(token);
  const widest = Math.max(...people.map((p) => p.account_count));
  const candidates = people.filter((p) => p.account_count === widest);
  // The README caption tells the "privileged, MFA off, every app" story, and
  // Grace Hopper is the persona docs/demo.md and the walkthrough use for it.
  const person =
    candidates.find((p) => p.display_name === "Grace Hopper" && p.privileged && !p.mfa_enabled) ??
    candidates.find((p) => p.privileged && !p.mfa_enabled) ??
    candidates.find((p) => p.privileged) ??
    candidates[0];

  const departed = await api(token, "/findings?policy_slug=cross-app-departed-still-has-access&status=open&limit=50");
  // Katherine Johnson is the drift timeline's offboarding story (docs/demo.md).
  const finding = departed.items.find((f) => f.subject_label === "Katherine Johnson") ?? departed.items[0];

  const policies = await api(token, "/policies?limit=500");
  const policy = (policies.items ?? policies).find((p) => p.slug === "slack-privileged-without-mfa");

  if (!person || !finding || !policy) throw new Error("demo estate is missing a screenshot subject; run make demo-verify");
  return { person: person.id, finding: finding.id, policy: policy.id };
}

// file stem, route, viewport, and how to find where the content ends.
function shots(ids) {
  return [
    {
      name: "identity-access-graph",
      route: `/explore?focus=${ids.person}&focus_type=identity&direction=out&layout=hierarchical&depth=2&labels=compact`,
      width: 1600,
      height: 1000,
      settle: 2500,
    },
    { name: "findings", route: "/findings?severity=critical", width: 1780, height: 1000 },
    { name: "finding-detail", route: `/findings/${ids.finding}`, width: 1600, height: 1000 },
    { name: "changes", route: "/changes", width: 1600, height: 920 },
    { name: "policies", route: "/policies", width: 1600, height: 1000 },
    { name: "dashboard", route: "/dashboard", width: 1600, height: 1700, trim: "grid", settle: 2500 },
    { name: "integrations", route: "/connectors", width: 1600, height: 760 },
    { name: "identity-detail", route: `/identities/${ids.person}`, width: 1600, height: 1000 },
    { name: "policy-workbench", route: `/policies/${ids.policy}?tab=code`, width: 1600, height: 1000, settle: 2500 },
    { name: "policy-packs", route: "/policies/packs", width: 1600, height: 1000 },
    { name: "add-integration", route: "/connectors/new", width: 1600, height: 1000 },
  ];
}

// The lowest pixel that carries content. A dashboard is a react-grid-layout
// whose container reserves empty rows, so measure its items; everywhere else,
// measure leaf elements that render text or media, never layout containers.
async function contentBottom(page, trim) {
  return page.evaluate((mode) => {
    if (mode === "grid") {
      const items = [...document.querySelectorAll(".react-grid-item")];
      return Math.max(0, ...items.map((el) => el.getBoundingClientRect().bottom + window.scrollY));
    }
    let bottom = 0;
    const walker = document.createTreeWalker(document.querySelector("main") ?? document.body, NodeFilter.SHOW_ELEMENT);
    for (let el = walker.currentNode; el; el = walker.nextNode()) {
      const leafText = [...el.childNodes].some((n) => n.nodeType === Node.TEXT_NODE && n.textContent.trim());
      const media = ["svg", "canvas", "img", "input", "textarea", "button"].includes(el.tagName.toLowerCase());
      if (!leafText && !media) continue;
      const rect = el.getBoundingClientRect();
      if (rect.width === 0 || rect.height === 0) continue;
      const style = getComputedStyle(el);
      if (style.visibility === "hidden" || style.display === "none") continue;
      bottom = Math.max(bottom, rect.bottom + window.scrollY);
    }
    return bottom;
  }, trim ?? "leaf");
}

async function main() {
  const token = await login();
  const ids = await resolveIds(token);
  await mkdir(OUT_DIR, { recursive: true });

  const browser = await chromium.launch();
  try {
    for (const shot of shots(ids)) {
      if (ONLY && shot.name !== ONLY) continue;
      const context = await browser.newContext({
        viewport: { width: shot.width, height: shot.height },
        deviceScaleFactor: OUTPUT_WIDTH / shot.width,
        colorScheme: "dark",
        reducedMotion: "reduce",
      });
      await context.addCookies([{ name: "kestrel_session", value: token, url: WEB_URL, httpOnly: true, sameSite: "Lax" }]);
      // Before first paint, so the theme script never flashes the light theme.
      await context.addInitScript(() => {
        try {
          localStorage.setItem("kestrel-theme", "dark");
        } catch {}
      });
      const page = await context.newPage();
      await page.goto(`${WEB_URL}${shot.route}`, { waitUntil: "networkidle" });
      if (new URL(page.url()).pathname.startsWith("/login")) throw new Error(`${shot.name}: bounced to login`);
      await page.evaluate(() => document.fonts.ready);
      await page.waitForTimeout(shot.settle ?? 1200);
      // Toasts and the live unread badge are noise in a still image.
      await page.addStyleTag({ content: "[data-sonner-toaster],[role=status][aria-live],.sidebar-bell>span{display:none!important}" });

      const bottom = Math.ceil(await contentBottom(page, shot.trim));
      const height = Math.min(shot.height, Math.max(200, bottom + BOTTOM_PADDING));
      const file = path.join(OUT_DIR, `${shot.name}.png`);
      await page.screenshot({ path: file, clip: { x: 0, y: 0, width: shot.width, height } });
      console.log(`${shot.name}.png  ${OUTPUT_WIDTH}x${Math.round((height * OUTPUT_WIDTH) / shot.width)}  ${shot.route}`);
      await context.close();
    }
  } finally {
    await browser.close();
  }
}

main().catch((err) => {
  console.error(`capture-screenshots: ${err.message}`);
  process.exit(1);
});
