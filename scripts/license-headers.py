"""Add or check the Apache-2.0 header on every tracked source file.

    python3 scripts/license-headers.py           # add the header where it is missing
    python3 scripts/license-headers.py --check   # exit 1 if any file lacks it

The header goes after a shebang, an encoding line, or a Dockerfile parser
directive, which must stay first. Files that tools generate are skipped, and so
are the paths a downstream repository lists in .downstream-paths.
Standard library only, so CI's hygiene job can run it without `uv sync`.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINES = ("Copyright 2026 The Kestrel Authors", "SPDX-License-Identifier: Apache-2.0")

# Comment prefix and suffix per file kind.
HASH = ("# ", "")
SLASH = ("// ", "")
CSS = ("/* ", " */")
STYLES = {
    ".py": HASH,
    ".mako": HASH,
    ".sh": HASH,
    ".ts": SLASH,
    ".tsx": SLASH,
    ".js": SLASH,
    ".mjs": SLASH,
    ".mts": SLASH,
    ".css": CSS,
}

# Generated by tools; rewritten on their next run.
SKIP = {"apps/web/next-env.d.ts"}

# Lines that must stay above the header.
KEEP_FIRST = re.compile(r"^(#!|#.*coding[:=]|# ?(syntax|escape|check)=)")


def style_for(path: str) -> tuple[str, str] | None:
    name = Path(path).name
    if name == "Makefile" or name.endswith("Dockerfile"):
        return HASH
    return STYLES.get(Path(path).suffix)


def downstream_paths() -> list[str]:
    """Paths a downstream repository owns (.downstream-paths; see oss-hygiene.sh).

    They are that repository's own material, not Kestrel source, so they carry
    whatever license it chooses. A trailing slash means a directory.
    """
    file = ROOT / ".downstream-paths"
    if not file.is_file():
        return []
    lines = (line.split("#", 1)[0].strip() for line in file.read_text(encoding="utf-8").splitlines())
    return [line for line in lines if line]


def is_downstream(path: str, owned: list[str]) -> bool:
    return any(path.startswith(o) if o.endswith("/") else path == o for o in owned)


def tracked_files() -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    owned = downstream_paths()
    return [
        p
        for p in out.split("\0")
        if p and p not in SKIP and not is_downstream(p, owned) and style_for(p) and (ROOT / p).is_file()
    ]


def has_header(text: str) -> bool:
    return "SPDX-License-Identifier:" in "\n".join(text.splitlines()[:5])


def with_header(text: str, style: tuple[str, str]) -> str:
    prefix, suffix = style
    header = "".join(f"{prefix}{line}{suffix}\n" for line in LINES)
    lines = text.splitlines(keepends=True)
    keep = 0
    while keep < len(lines) and keep < 2 and KEEP_FIRST.match(lines[keep]):
        keep += 1
    return "".join(lines[:keep]) + header + "".join(lines[keep:])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail instead of writing when a header is missing")
    args = ap.parse_args()

    missing = []
    for path in tracked_files():
        file = ROOT / path
        text = file.read_text(encoding="utf-8")
        if has_header(text):
            continue
        missing.append(path)
        if not args.check:
            file.write_text(with_header(text, style_for(path)), encoding="utf-8")  # type: ignore[arg-type]

    if not missing:
        print("license headers present")
        return 0
    if args.check:
        print("license-headers: missing the Apache-2.0 header:", *missing, sep="\n  ", file=sys.stderr)
        print("run: python3 scripts/license-headers.py", file=sys.stderr)
        return 1
    print(f"license headers added to {len(missing)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
